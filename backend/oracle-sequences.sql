-- Execute uma unica vez no schema Oracle que a aplicacao utiliza.
-- Este script pressupoe que as tabelas estejam vazias.
-- Se houver dados, inicie cada sequencia em MAX(ID) + 1 para evitar IDs duplicados.

-- Necessario quando as colunas foram criadas como GENERATED AS IDENTITY.
ALTER TABLE USUARIO MODIFY (ID_USUARIO DROP IDENTITY);
ALTER TABLE CONTA MODIFY (ID_CONTA DROP IDENTITY);
ALTER TABLE DESPESA MODIFY (ID_DESPESA DROP IDENTITY);
ALTER TABLE RECEITA MODIFY (ID_RECEITA DROP IDENTITY);
ALTER TABLE INVESTIMENTO MODIFY (ID_INVESTIMENTO DROP IDENTITY);

CREATE SEQUENCE SEQ_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_CONTA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_DESPESA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_RECEITA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_INVESTIMENTO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
